def main():
    meta = pd.read_parquet(META)
    by_id = {int(r["id"]): r for _, r in meta.iterrows()}

    missing = sorted({i for _, _, ids, _ in ROWS for i in ids if i not in by_id})
    if missing:
        raise SystemExit(f"supporting ids not present in the corpus: {missing}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        for query, kind, ids, note in ROWS:
            link = str(by_id[ids[0]].get("link", "")).strip()
            f.write(
                json.dumps(
                    {
                        "query": query,
                        "expected_verdict": "derived",
                        "kind": kind,
                        "supporting_ids": ids,
                        "note": note,
                        "source": link,
                    },
                    ensure_ascii=False,
                )
                + "\n"
            )

    kinds = {k: sum(1 for _, kk, _, _ in ROWS if kk == k) for _, k, _, _ in ROWS}
    print(f"wrote {len(ROWS)} rows to {OUT}  {kinds}")


if __name__ == "__main__":
    main()
