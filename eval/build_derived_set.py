"""Build eval/datasets/derived.jsonl — the false-abstention guard set.

These are questions with NO verbatim match in the corpus that are nonetheless
answerable by deriving from fatwas that are in it. Correct behavior is verdict
``derived`` with citations — never ``abstain``. Measured against the spec's
requirement that "no exact match" must not mean "no answer".

Curation method (deliberately NOT using the dense retriever, which would make
the later top-8 retrieval check circular):
  1. Anchor fatwas were located by lexical keyword search over the corpus.
  2. Each anchor was read to confirm it genuinely determines the derived answer.
  3. The eval query is then written in different words — dialect, a narrower
     case, or an application — so retrieval is actually being tested.

``source`` is filled from the corpus's own binbaz.org.sa link for the first
supporting fatwa, so every row is traceable to the published fatwa.

Three kinds, 20 each:
  dialect     — same question, colloquial Gulf phrasing
  narrower    — a specific sub-case the general ruling settles
  application — applying the ruling to the asker's concrete situation
"""

